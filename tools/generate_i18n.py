"""Generate offline translation catalogs; --check verifies generated assets.

Edit the JSON sources. Reference: betamoojw/BETTA-HA-PANEL-4-Guiton-ESP32S3,
Chinese commit 4e117ca and European-language dev revision db764156; extended
for the current fork. Existing English/German catalogs remain handwritten.
No translation service is used at build or run time.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "/* SPDX-License-Identifier: LicenseRef-FNCL-1.1\n * Copyright (c) 2026 andre68723\n * Generated by tools/generate_i18n.py; edit the JSON catalog.\n */\n"


def outputs():
    for code in ("es", "fr", "pl", "zh-cn", "zh-tw"):
        data = json.loads((ROOT / "main/i18n" / f"{code}.json").read_text(encoding="utf-8"))
        parts = ['{"lvgl":{']
        sections = list(data["lvgl"].items())
        for i, (key, value) in enumerate(sections):
            parts.append(json.dumps(key) + ':' + json.dumps(value, ensure_ascii=False, separators=(',', ':')) + (',' if i < len(sections)-1 else ''))
        parts.append('}}')
        symbol = 'I18N_BUILTIN_' + code.upper().replace('-', '_')
        text = HEADER + f'static const char {symbol}[] =\n' + '\n'.join('    ' + json.dumps(s, ensure_ascii=False) for s in parts) + ';\n'
        yield ROOT / 'main/i18n' / f'{code}.inc', text
        data = json.loads((ROOT / 'components/webui/i18n' / f'{code}.json').read_text(encoding='utf-8'))
        yield ROOT / 'components/webui/www/js' / f'i18n-{code}.js', HEADER + f'WEB_I18N_BUILTIN["{code}"] = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    failures = 0
    for path, text in outputs():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                print('FAIL stale catalog:', path.relative_to(ROOT))
                failures += 1
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
    print('Translation catalog assets:', 'FAIL' if failures else 'OK')
    return bool(failures)


if __name__ == '__main__':
    raise SystemExit(main())
