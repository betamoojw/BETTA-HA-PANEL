"""Regenerate the firmware table from the vendored timezone database."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / 'main/net/tzdb'


def load_date_patterns():
    patterns = {}
    for line in (DB / 'date_patterns.txt').read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'):
            continue
        _, pattern, *names = line.split()
        assert len(pattern) == 5 and sorted(pattern[::2]) == ['D', 'M', 'Y']
        assert pattern[1] == pattern[3] and pattern[1] in './-'
        for name in names:
            assert name not in patterns, name
            patterns[name] = pattern
    return patterns


def generate():
    zones = json.loads((DB / 'zones.json').read_text(encoding='utf-8'))
    assert zones and all(isinstance(k, str) and isinstance(v, str) and
                         0 < len(k) < 128 and 0 < len(v) < 128
                         for k, v in zones.items())
    patterns = load_date_patterns()
    assert patterns.keys() == zones.keys(), 'Timezone/date profile mismatch'
    return ('/* Generated by tools/generate_timezones.py; do not edit. */\n' +
            ''.join('    {%s, %s, %s},\n' % (json.dumps(k), json.dumps(v), json.dumps(patterns[k]))
                    for k, v in sorted(zones.items())))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        assert (DB / 'zones.inc').read_text(encoding='utf8') == generate(), 'Stale timezone table'
    else:
        (DB / 'zones.inc').write_text(generate(), encoding='utf-8', newline='\n')
