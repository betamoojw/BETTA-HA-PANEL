"""Verify and embed Panel10's precompressed, lossless UI CJK subset."""
import argparse
from pathlib import Path
import zlib

MAX_FONT_BYTES = 512 * 1024


def generate(source, output, packed_source):
    data = source.read_bytes()
    if not 12 <= len(data) <= MAX_FONT_BYTES or data[:4] != b"\0\1\0\0":
        raise ValueError("CJK subset must be a bounded TrueType font")
    packed = packed_source.read_bytes()
    mismatch = ("Packed CJK font does not match the source TTF; "
                "regenerate it as documented in main/ui/fonts/README.md")
    if not 0 < len(packed) <= MAX_FONT_BYTES:
        raise ValueError(mismatch)
    decoder = zlib.decompressobj()
    try:
        decoded = decoder.decompress(packed, len(data) + 1)
    except zlib.error as error:
        raise ValueError(mismatch) from error
    if decoded != data or not decoder.eof or decoder.unused_data or decoder.unconsumed_tail:
        raise ValueError(mismatch)
    lines = [
        "/* Generated by tools/pack_cjk_font.py; do not edit.",
        " * SPDX-License-Identifier: OFL-1.1",
        " * Noto Sans SC subset, Copyright 2014-2021 Adobe (http://www.adobe.com/),",
        " * Reserved Font Name Source. See main/ui/fonts/NOTO_CJK-OFL.txt. */",
        f"#define CJK_FONT_RAW_SIZE {len(data)}U",
        "static const unsigned char cjk_font_packed[] = {",
    ]
    lines.extend("    " + ",".join(f"0x{byte:02x}" for byte in packed[i:i + 24]) + ","
                 for i in range(0, len(packed), 24))
    lines.extend(["};", ""])
    text = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8", newline="\n")
    return len(data), len(packed)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--packed-source", type=Path, required=True)
    args = parser.parse_args()
    raw, packed = generate(args.source, args.output, args.packed_source)
    print(f"Panel10 CJK subset: {raw} -> {packed} bytes ({raw - packed} saved before code/alignment)")
