"""Losslessly pack the five generated LVGL catalogs for panel10's existing zlib decoder."""
import argparse
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ("es", "fr", "pl", "zh-cn", "zh-tw")
MAX_JSON_BYTES = 32768


def catalog_bytes(path):
    document = json.loads(path.read_text(encoding="utf-8"))
    data = json.dumps({"lvgl": document["lvgl"]}, ensure_ascii=False,
                      separators=(",", ":")).encode("utf-8")
    if not 0 < len(data) <= MAX_JSON_BYTES or b"\0" in data:
        raise ValueError("Catalog exceeds the firmware JSON limit or contains NUL: " + str(path))
    return data


def generate(source, output):
    lines = ["/* Generated by tools/pack_i18n.py; original catalog attribution is retained in main/i18n. */",
             "/* SPDX-License-Identifier: LicenseRef-FNCL-1.1 | Copyright (c) 2026 andre68723 */"]
    entries = []
    raw_total = packed_total = 0
    for code in LANGUAGES:
        data = catalog_bytes(source / (code + ".json"))
        packed = zlib.compress(data, 9)
        if zlib.decompress(packed) != data:
            raise ValueError("Catalog compression round trip failed: " + code)
        symbol = "i18n_packed_" + code.replace("-", "_")
        lines.append(f"static const unsigned char {symbol}[] = {{")
        lines.extend("    " + ",".join(f"0x{b:02x}" for b in packed[i:i+24]) + ","
                     for i in range(0, len(packed), 24))
        lines.append("};")
        entries.append(f'    {{"{code}", {symbol}, sizeof({symbol}), {len(data)}}},')
        raw_total += len(data) + 1
        packed_total += len(packed)
    lines.extend(["static const struct {",
                  "    const char *code; const unsigned char *data; size_t size; size_t json_size;",
                  "} i18n_packed_catalogs[] = {", *entries, "};", ""])
    text = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8", newline="\n")
    return raw_total, packed_total


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    raw, packed = generate(ROOT / "main/i18n", args.output)
    print(f"Panel10 translation payloads: {raw} -> {packed} bytes ({raw - packed} saved before code/alignment)")
