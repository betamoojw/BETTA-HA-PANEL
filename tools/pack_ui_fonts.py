"""Verify and embed Panel10's precompressed UI TrueType subsets."""
import argparse
from pathlib import Path
import zlib
from generate_widget_fonts import FONTS

MAX_FONT_BYTES = 512 * 1024


def generate(source, output, packed_source, face="cjk"):
    meta = FONTS[face]
    data = source.read_bytes()
    if not 12 <= len(data) <= MAX_FONT_BYTES or data[:4] != b"\0\1\0\0":
        raise ValueError(f"{source.name} must be a bounded TrueType font")
    packed = packed_source.read_bytes()
    mismatch = (f"{packed_source.name} does not match the source TTF {source.name}; "
                "regenerate it as documented in main/ui/fonts/README.md")
    if not 0 < len(packed) <= MAX_FONT_BYTES:
        raise ValueError(mismatch)
    decoder = zlib.decompressobj()
    try:
        decoded = decoder.decompress(packed, len(data) + 1)
    except zlib.error as error:
        raise ValueError(mismatch) from error
    if decoded != data or not decoder.eof or decoder.unused_data or decoder.unconsumed_tail:
        raise ValueError(mismatch)
    lines = [
        "/* Generated by tools/pack_ui_fonts.py; do not edit.",
        " * SPDX-License-Identifier: " + ("Apache-2.0" if meta["license"].startswith("Apache") else "OFL-1.1"),
        f" * {meta['title']}, {meta['copyright']}.",
        f" * {meta['license']} */",
        f"#define {face.upper()}_FONT_RAW_SIZE {len(data)}U",
        f"static const unsigned char {face}_font_packed[] = {{",
    ]
    lines.extend("    " + ",".join(f"0x{byte:02x}" for byte in packed[i:i + 24]) + ","
                 for i in range(0, len(packed), 24))
    lines.extend(["};", ""])
    text = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8", newline="\n")
    return len(data), len(packed)


def generate_all(directory, output):
    for face, meta in FONTS.items():
        source = directory / meta["subset"]
        generate(source, output / f"{face}_font_packed.h", source.with_suffix(".ttf.zlib"), face)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font_directory", type=Path)
    parser.add_argument("output_directory", type=Path)
    args = parser.parse_args()
    generate_all(args.font_directory, args.output_directory)
