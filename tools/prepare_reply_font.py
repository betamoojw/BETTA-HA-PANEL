"""Reproduce/check/extract the pinned offline Xiaozhi transcript font resource."""
import argparse
import gzip
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "main/ui/fonts"
SOURCE_SHA = "d68bafcb48a2707749396aa12bbbd833cb70401f3a9a689fd2902c7e0d295964"


def verified_resource():
    meta = json.loads((FONTS / "cjk_reply_manifest.json").read_text())
    packed = (FONTS / "noto_cjk_reply.ttf.gz").read_bytes()
    if hashlib.sha256(packed).hexdigest() != meta["gzip_sha256"]:
        raise ValueError("Compressed resource checksum mismatch")
    raw = gzip.decompress(packed)
    if len(raw) != meta["bytes"] or hashlib.sha256(raw).hexdigest() != meta["sha256"]:
        raise ValueError("Font resource checksum mismatch")
    header = (FONTS / "cjk_reply_resource.h").read_text()
    if meta["sha256"] not in header or str(len(raw)) not in header or meta["path"] not in header:
        raise ValueError("Firmware resource identity differs")
    return raw, meta


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="Pinned NotoSansSC-VF.ttf; regenerate maintained resource")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--extract", type=Path, help="Verified local TTF for rendering/installation; never overwrite differing data")
    args = parser.parse_args()
    if args.source:
        from fontTools.ttLib import TTFont
        from generate_widget_fonts import subset_font
        if hashlib.sha256(args.source.read_bytes()).hexdigest() != SOURCE_SHA:
            raise ValueError("Unexpected source font")
        points = {cp for cp in TTFont(args.source).getBestCmap() if cp >= 0x3000}
        raw = subset_font(args.source, points, [], 400)
        sha = hashlib.sha256(raw).hexdigest()
        stream = io.BytesIO()
        with gzip.GzipFile(filename="", mode="wb", fileobj=stream, mtime=0, compresslevel=9) as f:
            f.write(raw)
        packed = stream.getvalue()
        meta = dict(source="Noto Sans SC variable TrueType 2.004", source_sha256=SOURCE_SHA,
                    weight=400, codepoints=len(points), bytes=len(raw), sha256=sha,
                    gzip_sha256=hashlib.sha256(packed).hexdigest(), path=f"/littlefs/xiaozhi-cjk-{sha[:12]}.ttf")
        (FONTS / "noto_cjk_reply.ttf.gz").write_bytes(packed)
        (FONTS / "cjk_reply_manifest.json").write_text(json.dumps(meta, indent=2) + "\n")
        (FONTS / "cjk_reply_resource.h").write_text(
            '/* SPDX-License-Identifier: LicenseRef-FNCL-1.1\n * Copyright (c) 2026 andre68723\n'
            ' * Generated by tools/prepare_reply_font.py; do not edit.\n */\n#pragma once\n'
            f'#define CJK_REPLY_BYTES {len(raw)}U\n#define CJK_REPLY_SHA256 "{sha}"\n#define CJK_REPLY_PATH "{meta["path"]}"\n')
    raw, meta = verified_resource()
    if args.check:
        from fontTools.ttLib import TTFont
        cmap = TTFont(io.BytesIO(raw)).getBestCmap()
        assert len(cmap) == meta["codepoints"]
        samples = "今天是星期天喔，十月二十五号。出门记得带雨伞，看起来可能会下点雨。"
        samples += "請攜帶雨傘，臺灣與香港的天氣預報：憂鬱、蘋果、鬧鐘、龍、龜、麵包。"
        assert all(ord(c) in cmap for c in samples)
    if args.extract:
        if args.extract.exists() and args.extract.read_bytes() != raw:
            raise ValueError("Refusing to replace an existing different file")
        args.extract.write_bytes(raw)
    print(f'Reply font verified: {meta["codepoints"]} codepoints, {len(raw)} bytes, SHA256 {meta["sha256"]}')


if __name__ == "__main__":
    main()
